#include "push_swap.h"

int	ft_has_duplicate(t_node *a, int value) // 1 → 有重复 0 → 没有重复
{
	while (a)
	{
		if (a->value == value) // 如果 a->value == value 怎么办？
			return (1);
		a = a->next;
	}
	return (0); // 全部找完都没找到怎么办？
}