#include "libft.h"

int	ft_atoi(const char *str)
{
	int		t;
	long	i;

	i = 0;
	t = 1;
	while (*str && ((*str == ' ') || (*str >= '\t' && *str <= '\r')))
		str++;
	if (*str == '-')
	{
		t = -1;
		str++;
	}
	else if (*str == '+')
		str++;
	while (*str && (*str >= '0' && *str <= '9'))
	{
		i = i * 10 + (*str - '0');
		str++;
	}
	return ((int)(i * t));
}
