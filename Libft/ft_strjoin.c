#include "libft.h"

char	*ft_strjoin(char const *s1, char const *s2)
{
	char	*p;
	size_t	len1;
	size_t	len2;

	len1 = ft_strlen(s1);
	len2 = ft_strlen(s2);
	p = malloc(len1 + len2 + 1);
	if (!p)
		return (NULL);
	ft_memcpy(p, s1, len1);
	ft_memcpy(&p[len1], s2, len2);
	p[len1 + len2] = '\0';
	return (p);
}
